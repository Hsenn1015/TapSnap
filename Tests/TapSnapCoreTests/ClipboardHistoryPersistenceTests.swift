import AppKit
import XCTest
@testable import TapSnapApp

final class ClipboardHistoryPersistenceTests: XCTestCase {
    private func storage() -> URL {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("TapSnap-ClipboardTests-\(UUID())")
        addTeardownBlock { try? FileManager.default.removeItem(at: url) }
        return url
    }

    private func pasteboard() -> NSPasteboard {
        let board = NSPasteboard.withUniqueName()
        addTeardownBlock { board.releaseGlobally() }
        return board
    }

    private func write(_ text: String, to board: NSPasteboard, history: ClipboardHistory) {
        board.clearContents()
        board.setString(text, forType: .string)
        history.poll()
    }

    private func writeImage(to board: NSPasteboard, history: ClipboardHistory) throws {
        let context = try XCTUnwrap(CGContext(data: nil, width: 12, height: 10, bitsPerComponent: 8, bytesPerRow: 48,
                                            space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        context.setFillColor(CGColor(gray: 0.5, alpha: 1))
        context.fill(CGRect(x: 0, y: 0, width: 12, height: 10))
        let image = try XCTUnwrap(context.makeImage())
        let png = try XCTUnwrap(NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:]))
        board.clearContents()
        board.setData(png, forType: .png)
        history.poll()
    }

    func testTextAndImagePersistAndActivateWithoutDuplicatingHistory() throws {
        let directory = storage()
        let board = pasteboard()
        let history = ClipboardHistory(storageDirectory: directory, pasteboard: board)
        write("本地历史", to: board, history: history)
        try writeImage(to: board, history: history)
        history.stop()
        let restored = ClipboardHistory(storageDirectory: directory, pasteboard: board)
        XCTAssertEqual(restored.entries.count, 2)
        let imageEntry = try XCTUnwrap(restored.entries.first)
        let textEntry = try XCTUnwrap(restored.entries.last)
        if case .image(let image) = imageEntry.content {
            XCTAssertEqual(image.width, 12)
            XCTAssertEqual(image.height, 10)
        } else { XCTFail("应恢复图片") }
        restored.activate(textEntry)
        restored.poll()
        XCTAssertEqual(board.string(forType: .string), "本地历史")
        XCTAssertEqual(restored.entries.count, 2)
        restored.stop()
        let attributes = try FileManager.default.attributesOfItem(atPath: directory.appendingPathComponent("manifest.json").path)
        XCTAssertEqual((attributes[.posixPermissions] as? NSNumber)?.intValue, 0o600)
    }

    func testClearRemovesPersistedImagesAndTextImmediately() throws {
        let directory = storage()
        let board = pasteboard()
        let history = ClipboardHistory(storageDirectory: directory, pasteboard: board)
        write("will be removed", to: board, history: history)
        try writeImage(to: board, history: history)
        history.stop()
        history.clear()
        let restored = ClipboardHistory(storageDirectory: directory, pasteboard: board)
        XCTAssertTrue(restored.entries.isEmpty)
        let files = try FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil)
        XCTAssertTrue(files.filter { $0.pathExtension == "png" }.isEmpty)
        let metadata = try String(contentsOf: directory.appendingPathComponent("manifest.json"), encoding: .utf8)
        XCTAssertFalse(metadata.contains("will be removed"))
        restored.stop()
    }

    func testConcealedAndTransientContentsAreNotRecorded() {
        let directory = storage()
        let board = pasteboard()
        let history = ClipboardHistory(storageDirectory: directory, pasteboard: board)
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            board.clearContents()
            board.setString("private", forType: .string)
            board.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
            history.poll()
        }
        XCTAssertTrue(history.entries.isEmpty)
        history.stop()
    }

    func testCapacityAndByteBudgetPruneOldEntries() {
        let directory = storage()
        let board = pasteboard()
        let history = ClipboardHistory(storageDirectory: directory, pasteboard: board)
        for index in 0..<60 { write("item \(index)", to: board, history: history) }
        XCTAssertEqual(history.entries.count, ClipboardHistory.capacity)
        history.stop()
        let budgetHistory = ClipboardHistory(storageDirectory: directory.appendingPathComponent("bounded"), pasteboard: board, byteLimit: 64)
        write(String(repeating: "a", count: 40), to: board, history: budgetHistory)
        write(String(repeating: "b", count: 40), to: board, history: budgetHistory)
        XCTAssertEqual(budgetHistory.entries.count, 1)
        write(String(repeating: "c", count: 100), to: board, history: budgetHistory)
        XCTAssertEqual(budgetHistory.entries.count, 1)
        budgetHistory.stop()
        let restored = ClipboardHistory(storageDirectory: directory.appendingPathComponent("bounded"), pasteboard: board, byteLimit: 64)
        XCTAssertEqual(restored.entries.count, 1)
        restored.stop()
    }

    func testCorruptManifestDoesNotPreventNewHistory() throws {
        let directory = storage()
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        try Data("invalid".utf8).write(to: directory.appendingPathComponent("manifest.json"))
        let board = pasteboard()
        let history = ClipboardHistory(storageDirectory: directory, pasteboard: board)
        XCTAssertTrue(history.entries.isEmpty)
        write("recovered", to: board, history: history)
        history.stop()
        let restored = ClipboardHistory(storageDirectory: directory, pasteboard: board)
        XCTAssertEqual(restored.entries.count, 1)
        restored.stop()
    }
}
