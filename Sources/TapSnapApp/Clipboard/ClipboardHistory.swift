import AppKit
import Foundation
import TapSnapCore
import TapSnapImageIO

/// 本机剪贴板历史，最多 50 条、128 MB 解码内容；清空同时删除落盘内容。
final class ClipboardHistory: ObservableObject {
    struct Entry: Identifiable {
        enum Content {
            case text(String)
            case image(CGImage)
        }
        let id: UUID
        let date: Date
        let content: Content

        init(id: UUID = UUID(), date: Date, content: Content) {
            self.id = id
            self.date = date
            self.content = content
        }
    }

    enum Filter: String, CaseIterable {
        case all = "全部", images = "图片", text = "文字"

        func includes(_ entry: Entry) -> Bool {
            switch (self, entry.content) {
            case (.all, _), (.images, .image), (.text, .text): return true
            default: return false
            }
        }
    }

    private struct SavedEntry: Codable {
        let id: UUID
        let date: Date
        let text: String?
    }
    private struct Manifest: Codable { var entries: [SavedEntry] }

    static let capacity = 50
    static let maximumTextLength = 20_000
    static let maximumContentBytes = 128 * 1_024 * 1_024
    @Published private(set) var entries: [Entry] = []
    private let archive: LocalImageArchive<Manifest>
    private let pasteboard: NSPasteboard
    private let byteLimit: Int
    private var timer: Timer?
    private var lastChangeCount: Int

    init(storageDirectory: URL = AppPaths.applicationSupport.appendingPathComponent("clipboard-history", isDirectory: true),
         pasteboard: NSPasteboard = .general, byteLimit: Int = ClipboardHistory.maximumContentBytes) {
        archive = LocalImageArchive(directory: storageDirectory)
        self.pasteboard = pasteboard
        self.byteLimit = byteLimit
        lastChangeCount = pasteboard.changeCount
        if let manifest = archive.load() {
            entries = manifest.entries.prefix(Self.capacity).compactMap { stored in
                if let text = stored.text {
                    return Entry(id: stored.id, date: stored.date, content: .text(String(text.prefix(Self.maximumTextLength))))
                }
                guard let image = archive.image(stored.id) else { return nil }
                return Entry(id: stored.id, date: stored.date, content: .image(image))
            }
            enforceLimit()
        }
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        archive.flush()
    }

    func clear() {
        entries.removeAll()
        persist()
        archive.flush()
    }

    /// 把某一条放回剪贴板，不把自己恢复的内容再次收录。
    func activate(_ entry: Entry) {
        pasteboard.clearContents()
        switch entry.content {
        case .text(let text): pasteboard.setString(text, forType: .string)
        case .image(let image):
            if let data = try? ImageCodec.encode(image, as: .png) { pasteboard.setData(data, forType: .png) }
        }
        lastChangeCount = pasteboard.changeCount
    }

    func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        // 遵从密码管理器及来源应用标注的私密/临时剪贴板内容。
        let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !privateTypes.contains(where: { pasteboard.types?.contains(NSPasteboard.PasteboardType($0)) == true }),
              let entry = makeEntry() else { return }
        append(entry)
    }

    private func makeEntry() -> Entry? {
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            return Entry(date: Date(), content: .text(String(text.prefix(Self.maximumTextLength))))
        }
        if let data = pasteboard.data(forType: .png), let image = try? ImageCodec.decode(data) {
            return Entry(date: Date(), content: .image(image))
        }
        if let data = pasteboard.data(forType: .tiff), let image = NSBitmapImageRep(data: data)?.cgImage {
            return Entry(date: Date(), content: .image(image))
        }
        return nil
    }

    private func append(_ entry: Entry) {
        if case .text(let incoming) = entry.content,
           case .text(let existing)? = entries.first?.content, incoming == existing { return }
        guard contentBytes(entry) <= byteLimit else { return }
        entries.insert(entry, at: 0)
        enforceLimit()
        persist()
    }

    private func contentBytes(_ entry: Entry) -> Int {
        switch entry.content {
        case .text(let text): return text.utf8.count
        case .image(let image): return image.bytesPerRow * image.height
        }
    }

    private func enforceLimit() {
        if entries.count > Self.capacity { entries.removeLast(entries.count - Self.capacity) }
        var bytes = entries.reduce(0) { $0 + contentBytes($1) }
        while bytes > byteLimit, let removed = entries.popLast() { bytes -= contentBytes(removed) }
    }

    private func persist() {
        var images: [UUID: CGImage] = [:]
        let stored = entries.map { entry -> SavedEntry in
            switch entry.content {
            case .text(let text): return SavedEntry(id: entry.id, date: entry.date, text: text)
            case .image(let image):
                images[entry.id] = image
                return SavedEntry(id: entry.id, date: entry.date, text: nil)
            }
        }
        archive.save(Manifest(entries: stored), images: images)
    }

    deinit { timer?.invalidate(); archive.flush() }
}
